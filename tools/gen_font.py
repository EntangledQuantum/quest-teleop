"""Regenerates client/core/font_data.h: one coverage atlas with three faces (ASCII 32..126) and their metrics.

    python tools/gen_font.py            (needs Pillow)

Faces: 0 = Host Grotesk Medium (titles, values, buttons), 1 = Host Grotesk
Regular (body), 2 = Martian Mono Regular (labels, data). Both families are under the SIL Open Font License; the
TTF files in tools/fonts are the latin subsets.
"""
import pathlib

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent
FACES = [("HostGrotesk-Medium.ttf", 56), ("HostGrotesk-Regular.ttf", 56), ("MartianMono-Regular.ttf", 44)]
FIRST, LAST, W, PAD = 32, 126, 1024, 2

glyphs, images = [], []
x = y = shelf = 0
for fi, (name, px) in enumerate(FACES):
    font = ImageFont.truetype(str(ROOT / "fonts" / name), px)
    ascent, descent = font.getmetrics()
    row = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        l, t, r, b = font.getbbox(ch)
        w, h = max(r - l, 0), max(b - t, 0)
        if x + w + 2 * PAD > W:
            x, y, shelf = 0, y + shelf, 0
        if w and h:
            im = Image.new("L", (w + 2 * PAD, h + 2 * PAD), 0)
            ImageDraw.Draw(im).text((PAD - l, PAD - t), ch, font=font, fill=255)
            images.append((x, y, im))
        # ox, oy: where the padded bitmap's top-left sits relative to the pen position and the line top
        row.append((x, y, w + 2 * PAD if w else 0, h + 2 * PAD if h else 0, l - PAD, t - PAD, font.getlength(ch)))
        x += w + 2 * PAD
        shelf = max(shelf, h + 2 * PAD)
    glyphs.append((px, ascent, descent, row))
    x, y, shelf = 0, y + shelf, 0
H = 1
while H < y:
    H *= 2
atlas = Image.new("L", (W, H), 0)
for gx, gy, im in images:
    atlas.paste(im, (gx, gy))
atlas.putpixel((W - 1, H - 1), 255)          # a solid texel for filled rectangles
atlas.putpixel((W - 2, H - 1), 255)
atlas.putpixel((W - 1, H - 2), 255)
atlas.putpixel((W - 2, H - 2), 255)
data = atlas.tobytes()
rle, k = [], 0
while k < len(data):
    j = k
    while j < len(data) and data[j] == data[k] and j - k < 255:
        j += 1
    rle += [j - k, data[k]]
    k = j
out = ROOT.parent / "client" / "core" / "font_data.h"
with open(out, "w") as f:
    f.write("// Generated by tools/gen_font.py (Host Grotesk, Martian Mono; SIL OFL). Do not edit.\n")
    f.write("#pragma once\n#include <cstdint>\nnamespace qt {\n")
    f.write("struct FontGlyph { uint16_t x, y, w, h; int16_t ox, oy; float adv; };\n")
    f.write("struct FontFace { float px, ascent, descent; FontGlyph g[%d]; };\n" % (LAST - FIRST + 1))
    f.write(f"constexpr int kFontFirst = {FIRST}, kFontLast = {LAST}, kFontFaces = {len(FACES)};\n")
    f.write(f"constexpr int kFontAtlasW = {W}, kFontAtlasH = {H};\n")
    f.write("static const FontFace kFonts[kFontFaces] = {\n")
    for px, a, d, row in glyphs:
        f.write(f"{{{px}.0f, {a}.0f, {d}.0f, {{\n")
        for g in row:
            f.write("{%d,%d,%d,%d,%d,%d,%.3ff}," % g)
        f.write("\n}},\n")
    f.write("};\n")
    f.write(f"constexpr int kFontRleSize = {len(rle)};\nstatic const uint8_t kFontRle[] = {{\n")
    for k in range(0, len(rle), 40):
        f.write(",".join(map(str, rle[k:k + 40])) + ",\n")
    f.write("};\n}  // namespace qt\n")
atlas.save(ROOT.parent / "build" / "font_atlas.png") if (ROOT.parent / "build").is_dir() else None
print(f"wrote {out}: atlas {W}x{H}, {len(rle)} bytes RLE")
